// 표기: "-숫자" = 구매가, "+숫자" = 판매가, "x" = 구매·판매 모두 불가
export const NOT_TRADABLE = "구매 및 판매 할 수 없는 아이템입니다";

export function parseShop(text: string): string[][] {
  return text
    .split("/")
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => {
      const m = entry.match(/^(.+?)\s+(x|[-+]\d+(?:,[-+]\d+)?)$/);
      if (!m) throw new Error(`상점가 데이터 형식 오류: ${entry}`);
      const [, name, prices] = m;
      if (prices === "x") return [name, NOT_TRADABLE, NOT_TRADABLE];
      const won = (sign: string) => {
        const p = prices.split(",").find((v) => v.startsWith(sign));
        return p ? `${Number(p.slice(1)).toLocaleString()}원` : null;
      };
      return [name, won("-") ?? "구매 불가", won("+") ?? "판매 불가"];
    });
}

